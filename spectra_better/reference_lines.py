def all_lines() -> List[Tuple[float, float, str]]:
    out = []
    for name, lines in LINES.items():
        for wl, inten in lines:
            out.append((wl, inten, name))
    out.sort()
    return out


def nearest_line(wl: float, tolerance: float = 1.0, sources=None) -> Tuple[float, str]:
    """Ближайшая справочная линия (λ, источник) или (nan, '') если нет в пределах допуска."""
    best = (float("nan"), "")
    best_d = tolerance
    for line, _i, name in all_lines():
        if sources and name not in sources:
            continue
        d = abs(line - wl)
        if d <= best_d:
            best, best_d = (line, name), d
    return best
